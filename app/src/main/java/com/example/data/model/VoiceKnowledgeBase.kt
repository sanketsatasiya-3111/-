    fun findAnswer(query: String): String {
        val clean = query.trim().lowercase()
        if (clean.isBlank()) {
            return "કૃપા કરીને તમારો સ્વાસ્થ્ય સંબંધિત પ્રશ્ન પૂછો અથવા નીચે આપેલા પ્રશ્નોમાંથી પસંદ કરો."
        }
        for (item in qaList) {
            if (clean.contains(item.questionGu.lowercase()) ||
                item.keywords.any { clean.contains(it.lowercase()) }
            ) {
                return item.answerGu
            }
        }
        return "ક્ષમા કરશો, આ બાબતે સામાન્ય આરોગ્ય સલાહ: નિયમિત સમતોલ આહાર, પૂરતું પાણી અને દૈનિક કસરત કરો. કોઈપણ ચોક્કસ બીમારી કે દવા માટે કૃપા કરીને તમારા ફેમિલી ડૉક્ટર અથવા નજીકના પ્રાથમિક આરોગ્ય કેન્દ્ર (PHC) નો સંપર્ક કરો."
    }
